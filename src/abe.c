// No-CRT helpers
static __forceinline void abe_memcpy(void* dst, const void* src, SIZE_T n) {
    // volatile destination: MSVC's loop->memcpy idiom recognition cannot fold
    // volatile stores into a CRT libcall (which a BOF loader can't resolve)
    volatile BYTE* d = (volatile BYTE*)dst;
    const BYTE* s = (const BYTE*)src;
    while (n--) *d++ = *s++;
}

/* NOTE: no wcslen-style zero-scan loops anywhere in this file. MSVC's idiom
 * recognition converts them into dispatched CRT helpers that reference
 * __ImageBase, which is unresolvable in a BOF COFF. Lengths are carried explicitly
 * (GetEnvironmentVariableW/RegGetValueW return them; appended literals are
 * compile-time sized). */

static const char B64SET[] =
    "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

static DWORD b64_decode(const char* in, SIZE_T inlen, BYTE* out, SIZE_T outcap,
                        SIZE_T* outlen) {
    SIZE_T i = 0, o = 0;
    DWORD acc = 0; int bits = 0; int pad = 0;
    while (i < inlen) {
        char c = in[i++];
        if (c == '=') { pad++; continue; }
        if (c == '\r' || c == '\n' || c == ' ' || c == '\t') continue;
        const char* p = B64SET;
        int v = -1;
        while (*p) { if (*p == c) { v = (int)(p - B64SET); break; } p++; }
        if (v < 0) return 1; // bad char
        if (pad) return 1;   // data after padding
        acc = (acc << 6) | (DWORD)v;
        bits += 6;
        if (bits >= 8) {
            bits -= 8;
            if (o >= outcap) return 2;
            out[o++] = (BYTE)((acc >> bits) & 0xFF);
        }
    }
    *outlen = o;
    return 0;
}

static void b64_encode(const BYTE* in, SIZE_T inlen, char* out, SIZE_T outcap) {
    SIZE_T i = 0, o = 0;
    while (i + 3 <= inlen) {
        DWORD v = (in[i] << 16) | (in[i + 1] << 8) | in[i + 2];
        if (o + 4 > outcap) return;
        out[o++] = B64SET[(v >> 18) & 63];
        out[o++] = B64SET[(v >> 12) & 63];
        out[o++] = B64SET[(v >> 6) & 63];
        out[o++] = B64SET[v & 63];
        i += 3;
    }
    if (i < inlen && o + 4 <= outcap) {
        DWORD v = in[i] << 16;
        if (i + 1 < inlen) v |= in[i + 1] << 8;
        out[o++] = B64SET[(v >> 18) & 63];
        out[o++] = B64SET[(v >> 12) & 63];
        out[o++] = (i + 1 < inlen) ? B64SET[(v >> 6) & 63] : '=';
        out[o++] = '=';
    }
    if (o < outcap) out[o] = 0;
}

// scan haystack for ASCII needle (case-insensitive), returns index or -1
static LONG find_ascii_a(const char* hay, SIZE_T haylen, const char* needle) {
    SIZE_T n = 0;
    while (needle[n]) n++;
    if (n == 0 || haylen < n) return -1;
    for (SIZE_T i = 0; i + n <= haylen; i++) {
        SIZE_T j = 0;
        while (j < n) {
            char h = hay[i + j];
            char c = needle[j];
            if (h == c) { j++; continue; }
            if (h >= 'A' && h <= 'Z' && (char)(h + 32) == c) { j++; continue; }
            if (h >= 'a' && h <= 'z' && (char)(h - 32) == c) { j++; continue; }
            break;
        }
        if (j == n) return (LONG)i;
    }
    return -1;
}

